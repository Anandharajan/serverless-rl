"""Table + macros for the calibrated-scenario re-evaluation (results_v2_calibrated/)."""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

RES = Path(__file__).resolve().parent.parent / "results_v2_calibrated"
PAPER = Path(sys.argv[1])
ev = pd.read_csv(RES / "eval_active.csv")
B = json.loads((RES / "budgets.json").read_text())
info = json.loads((RES / "feasibility_summary.json").read_text())
ORDER = ["Static-Default", "Static-Best", "Static-Mix", "TargetTracking-PC", "Reactive-Rule",
         "Guardrail-Only", "MPC-EWMA", "PPO-Lag", "PPO-NoPC"]
KEY = {"Static-Default": "SD", "Static-Best": "SB", "Static-Mix": "SM", "TargetTracking-PC": "TT",
       "Reactive-Rule": "RR", "Guardrail-Only": "GO", "MPC-EWMA": "ME", "PPO-Lag": "PL", "PPO-NoPC": "NP"}
mac = {"CalBudgetActive": f"{B['active']:.3f}", "CalBudgetSlack": f"{B['slack']:.3f}",
       "CalBudgetTight": f"{B['tight']:.3f}"}
lines = []
for p in ORDER:
    g = ev[ev.policy == p]
    if g.empty:
        continue
    cells = [p + (r"$^\dagger$" if p == "Static-Best" else "")]
    for split in ("test", "test_unseen"):
        u = g[g.split == split]
        cells += [f"{100 * u.viol_rate.mean():.1f}", f"{u.cost_per_1k.mean():.4f}"]
    cells.append(f"{g.mem_changes.mean():.0f}")
    lines.append(" & ".join(cells) + r" \\")
    k = KEY[p]
    mac[f"CR{k}viol"] = f"{100 * g.viol_rate.mean():.1f}"
    mac[f"CR{k}violT"] = f"{100 * g[g.split == 'test'].viol_rate.mean():.1f}"
    mac[f"CR{k}violU"] = f"{100 * g[g.split == 'test_unseen'].viol_rate.mean():.1f}"
    mac[f"CR{k}cost"] = f"{g.cost_per_1k.mean():.4f}"
    mac[f"CR{k}costU"] = f"{g[g.split == 'test_unseen'].cost_per_1k.mean():.4f}"
    mac[f"CR{k}memch"] = f"{g.mem_changes.mean():.0f}"
    mac[f"CR{k}fb"] = f"{g.fallback_share.mean():.2f}"
    mac[f"CR{k}pc"] = f"{g.mean_pc.mean():.1f}"
(PAPER / "tables" / "calibrated.tex").write_text("\n".join(lines) + "\n")
# paired PPO-Lag vs Static-Mix and vs MPC
u = ev.groupby(["policy", "split", "fn", "day"]).mean(numeric_only=True).reset_index()
a = u[u.policy == "PPO-Lag"].set_index(["split", "fn", "day"]).viol_rate
for p in ("Static-Mix", "MPC-EWMA", "Reactive-Rule", "PPO-NoPC", "Guardrail-Only"):
    b = u[u.policy == p].set_index(["split", "fn", "day"]).viol_rate
    j = a.index.intersection(b.index)
    d = (a.loc[j] - b.loc[j]).values
    pv = 1.0 if np.allclose(d, 0) else stats.wilcoxon(a.loc[j], b.loc[j], zero_method="zsplit").pvalue
    mac[f"CRD{KEY[p]}"] = f"\\ensuremath{{{100 * d.mean():+.2f}}}"
    mac[f"CRP{KEY[p]}"] = f"{pv:.3f}" if pv >= 0.001 else "<0.001"
seeds = ev[ev.policy.str.startswith("PPO")].groupby(["policy", "seed"])[["viol_rate", "cost_per_1k", "mean_pc", "fallback_share"]].mean()
print(seeds.round(4))
acts = RES / "actions_seed0_active.csv.gz"
if acts.exists():
    A = pd.read_csv(acts)
    for p in ("PPO-Lag", "PPO-NoPC"):
        g = A[A.policy == p]
        top = g.groupby(["mem", "pc"]).size().sort_values(ascending=False) / len(g)
        mac[f"CRTop{KEY[p]}"] = ", ".join(f"{int(m)}\\,MB/PC {int(c)} ({100 * v:.0f}\\%)" for (m, c), v in top.head(2).items())
(PAPER / "calib_results_macros.tex").write_text("% generated by code/calib_results.py\n" + "\n".join(
    f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(mac.items())) + "\n")
print({k: v for k, v in mac.items()})
